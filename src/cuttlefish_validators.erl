-spec integer_value(
    Val :: integer_const() )
        -> integer() | badarg_error().
%% @doc Resolve a (possibly symbolic) integral value.
%%
%% Unless Val is an unrecognized symbolic constant, the result is always an
%% integer, even if the underlying erlang:system_info/1 call is allowed to
%% return a non-integral value.
%% Values obtained via non-trivial system calls and/or calculations are cached.
%%
%% Validators or translations can use this function to transparently map
%% integers and symbolic constants to known-valid integers efficiently.
%%
%% The recognized symbolic constants are:
%% <dl><dt>'cpus_count'</dt><dd>
%%  The number of logical processors (LCPUs) configured in the system, or '1'
%%  if the number cannot be determined.<br/>
%%  See <a
%%  href="https://www.erlang.org/doc/apps/erts/erlang#system_info_logical_processors"
%%  target="_blank">erlang:system_info(logical_processors)</a>
%% </dd><dt>'cpus_online'</dt><dd>
%%  The number of logical processors (LCPUs) online in the system, or the value
%%  of 'cpus_count' if the number cannot be determined.<br/>
%%  Always &lt;= 'cpus_count'.<br/>
%%  See <a
%%  href="https://www.erlang.org/doc/apps/erts/erlang#system_info_logical_processors_online"
%%  target="_blank">erlang:system_info(logical_processors_online)</a>
%% </dd><dt>'cpus_avail'</dt><dd>
%%  The number of logical processors (LCPUs) available in the system, which
%%  <em>MAY</em> be constrained by a CPU quota in effect, or the value of
%%  'cpus_online' if the number cannot be determined.<br/>
%%  Always &lt;= 'cpus_online'.<br/>
%%  See <a
%%  href="https://www.erlang.org/doc/apps/erts/erlang#system_info_logical_processors_available"
%%  target="_blank">erlang:system_info(logical_processors_available)</a><br/>
%%  See <a
%%  href="https://www.erlang.org/doc/apps/erts/erlang#system_info_cpu_quota"
%%  target="_blank">erlang:system_info(cpu_quota)</a>
%% </dd><dt>'kiloword'</dt><dd>
%%  'wordsize' x 1024.
%% </dd><dt>'wordsize'</dt><dd>
%%  The size of an emulator term word, in bytes.
%%  In nearly all cases, this is the CPU word (pointer) size.<br/>
%%  See <a
%%  href="https://www.erlang.org/doc/apps/erts/erlang#system_info_wordsize"
%%  target="_blank">erlang:system_info({wordsize, external})</a>
%% </dd></dl>
integer_value(CpuKey) when
        CpuKey =:= cpus_count; CpuKey =:= cpus_online; CpuKey =:= cpus_avail ->
    Key = {?MODULE, ?FUNCTION_NAME, CpuKey},
    case erlang:get(Key) of
        Val when erlang:is_integer(Val) ->
            Val;
        _ ->
            V = case CpuKey of
                cpus_avail ->
                    A = erlang:system_info(logical_processors_available),
                    Q = erlang:system_info(cpu_quota),
                    if
                        erlang:is_integer(Q) ->
                            if
                                erlang:is_integer(A) ->
                                    if
                                        Q < A ->
                                            Q;
                                        true ->
                                            A
                                    end;
                                true ->
                                    Q
                            end;
                        erlang:is_integer(A) ->
                            A;
                        true ->
                            integer_value(cpus_online)
                    end;
                cpus_online ->
                    O = erlang:system_info(logical_processors_online),
                    if
                        erlang:is_integer(O) ->
                            O;
                        true ->
                            integer_value(cpus_count)
                    end;
                _ ->
                    C = erlang:system_info(logical_processors),
                    if
                        erlang:is_integer(C) ->
                            C;
                        true ->
                            1
                    end
            end,
            erlang:put(Key, V),
            V
    end;
integer_value(kilobyte) ->
    1024;
integer_value(kiloword) ->
    io:format(user, "~n~ts:~ts:~b~n", [?MODULE, ?FUNCTION_NAME, ?LINE]),
    integer_value(wordsize) * 1024;
integer_value(wordsize) ->
    io:format(user, "~n~ts:~ts:~b~n", [?MODULE, ?FUNCTION_NAME, ?LINE]),
    Key = {?MODULE, ?FUNCTION_NAME, wordsize},
    case erlang:get(Key) of
        Val when erlang:is_integer(Val) ->
            Val;
        _ ->
            V = erlang:system_info({wordsize, external}),
            erlang:put(Key, V),
            V
    end;
integer_value(Val) when erlang:is_integer(Val) ->
    Val;
integer_value(Val) ->
    ?BADARG([Val]).

