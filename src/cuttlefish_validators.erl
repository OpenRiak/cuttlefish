-spec integer_compare(
    Op :: compare_op(), Val :: integer_const() )
        -> validator() | badarg_error().
%% @doc Generate a validator for the specified comparison.
%%
%% The name of the generated validator is derived from the comparison
%% operator and value (after resolution of symbolic constants).
%% For example, the validator generated by 'integer_compare(ge, 42)'
%% would be named "integer:&gt;=42".
integer_compare(Op, Val) ->
    case integer_value(Val) of
        V when erlang:is_integer(V) ->
            integer_compare(Op, V, erlang:integer_to_list(V));
        E ->
            E
    end.

-spec integer_range(
    Lo :: integer_const(), Hi :: integer_const() )
        -> validator() | badarg_error().
%% @doc Generate a validator for the specified range.
%%
%% The name of the generated validator is "integer:&lt;Lo&gt;..&lt;Hi&gt;"
%% (after resolution of symbolic constants).
%% @end
%% Recognize some common ranges built with literals.
integer_range(0, 65535) ->
    F = fun(V) ->
        erlang:is_integer(V) andalso V >= 0 andalso V =< 65535
    end,
    {validator, "integer:0..65535",
        "must be an integer in the range 0..65535", F};
integer_range(1024, 134217727) ->
    F = fun(V) ->
        erlang:is_integer(V) andalso V >= 1024 andalso V =< 134217727
    end,
    {validator, "integer:1024..134217727",
        "must be an integer in the range 1024..134217727", F};
%% Handle arbitrary integers.
integer_range(Lo, Hi) when erlang:is_integer(Lo), erlang:is_integer(Hi) ->
    if
        Lo =< Hi ->
            F = fun(V) ->
                erlang:is_integer(V) andalso V >= Lo andalso V =< Hi
            end,
            R = lists:concat([Lo, "..", Hi]),
            N = "integer:" ++ R,
            D = "must be an integer in the range " ++ R,
            {validator, N, D, F};
        true ->
            ?BADARG([Lo, Hi])
    end;
%% Handle symbolic constants.
integer_range(Lo, Hi)
        when (erlang:is_integer(Lo) orelse erlang:is_atom(Lo))
        andalso (erlang:is_integer(Hi) orelse erlang:is_atom(Hi)) ->
    L = integer_value(Lo),
    H = integer_value(Hi),
    if
        erlang:is_integer(L) andalso erlang:is_integer(H) ->
            integer_range(L, H);
        true ->
            ?BADARG([Lo, Hi])
    end;
integer_range(Lo, Hi) ->
    ?BADARG([Lo, Hi]).

-spec ip_address() -> validator().
%% @doc Generate a validator for the 'inet:ip_address()' type.
%%
%% The name of the generated validator is "ip-address".
ip_address() ->
    F = fun(Str) ->
        erlang:element(1, inet:parse_strict_address(Str)) =:= ok
    end,
    {validator, "ip-address",
        "must be a valid IPv4 or IPv6 address", F}.

-spec kilobyte_range(
    Lo :: integer(), Hi :: integer() )
        -> validator() | badarg_error().
%% @doc Generate a validator for the specified range scaled to kilobytes.
%%
%% The name of the generated validator is "bytesize:&lt;Lo&gt;KB..&lt;Hi&gt;KB".
kilobyte_range(Lo, Hi) when
        erlang:is_integer(Lo), erlang:is_integer(Hi), Lo =< Hi ->
    L = (Lo * 1024),
    H = (Hi * 1024),
    F = fun(V) ->
        erlang:is_integer(V) andalso V >= L andalso V =< H
    end,
    R = lists:concat([Lo, "KB..", Hi, "KB"]),
    N = "bytesize:" ++ R,
    D = "must be in the range " ++ R,
    {validator, N, D, F};
kilobyte_range(Lo, Hi) ->
    ?BADARG([Lo, Hi]).

-spec kiloword_range(
    Lo :: integer(), Hi :: integer() )
        -> validator() | badarg_error().
%% @doc Generate a validator for the specified range scaled to kilowords.
%% @equiv kilobyte_range(Lo * integer_value(wordsize), Hi * integer_value(wordsize))
kiloword_range(Lo, Hi) when
        erlang:is_integer(Lo), erlang:is_integer(Hi), Lo =< Hi ->
    Mult = integer_value(wordsize),
    kilobyte_range(Lo * Mult, Hi * Mult);
kiloword_range(Lo, Hi) ->
    ?BADARG([Lo, Hi]).

