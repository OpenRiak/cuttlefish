-type canned() :: #{{func_name(), arity()} => []}.
-type val_name() :: nonempty_string().
-type val_spec() :: val_name() | func_name() | {func_name(), func_args()}.

-spec canned() -> canned().
%% @hidden
%% @doc Returns the set of predefined validator functions.
canned() ->
    Key = {?MODULE, ?FUNCTION_NAME},
    case erlang:get(Key) of
        Val when erlang:is_map(Val) ->
            Val;
        _ ->
            Exports = module_info(exports),
            Exclude = [{module_info, 0}, {module_info, 1} | ?CANNED_EXCLUDE],
            Canned = maps:from_keys(Exports -- Exclude, []),
            erlang:put(Key, Canned),
            Canned
    end.

-spec integer_compare(
    Op :: compare_op(), Val :: integer(), VStr :: nonempty_string() )
        -> validator() | badarg_error().
%% @hidden
%% @doc Integer comparators from resolved integer_compare/2 parameters.
integer_compare(eq, Val, S) ->
    F = fun(V) -> V =:= Val end,
    {validator, "integer:==" ++ S, "must be an integer == " ++ S, F};
integer_compare(ge, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso V >= Val end,
    {validator, "integer:>=" ++ S, "must be an integer >= " ++ S, F};
integer_compare(gt, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso V > Val end,
    {validator, "integer:>" ++ S, "must be an integer > " ++ S, F};
integer_compare(le, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso V =< Val end,
    {validator, "integer:<=" ++ S, "must be an integer <= " ++ S, F};
integer_compare(lt, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso V < Val end,
    {validator, "integer:<" ++ S, "must be an integer < " ++ S, F};
integer_compare(mult, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso (V rem Val) =:= 0 end,
    {validator, "integer:mult" ++ S,
        "must be an integer evenly divisible by " ++ S, F};
integer_compare(ne, Val, S) ->
    F = fun(V) -> erlang:is_integer(V) andalso V =/= Val end,
    {validator, "integer:!=" ++ S, "must be an integer != " ++ S, F};
integer_compare(Op, _Val, _VStr) ->
    ?BADARG([Op]).

-spec resolve_validators(
    ValSpecs :: list(val_spec()),
    ValNames :: list(val_name()),
    Validators :: validators(),
    Errors :: list(cuttlefish_error:error()),
    Canned :: canned() )
        -> {list(val_name()), validators(), list(cuttlefish_error:error())}.
%% @hidden
%% @doc Resolve predefined validators in ValSpecs.
resolve_validators([Func | ValSpecs], ValNames, Validators, Errors, Canned)
        when erlang:is_atom(Func)
        andalso erlang:is_map_key({Func, 0}, Canned) ->
    %% Arity zero generators always return a valid constant validator spec.
    {validator, ValName, _, _} = ValSpec = ?MODULE:Func(),
    resolve_validators(
        ValSpecs, [ValName | ValNames],
        cuttlefish_validator:parse_and_merge(ValSpec, Validators),
        Errors, Canned);
resolve_validators(
    [{Func, Args} | ValSpecs], ValNames, Validators, Errors, Canned)
        when erlang:is_atom(Func) andalso erlang:is_list(Args)
        andalso erlang:is_map_key({Func, erlang:length(Args)}, Canned) ->
    case erlang:apply(?MODULE, Func, Args) of
        {validator, ValName, _, _} = ValSpec ->
            resolve_validators(
                ValSpecs, [ValName | ValNames],
                cuttlefish_validator:parse_and_merge(ValSpec, Validators),
                Errors, Canned);
        BadArg ->
            Error = {error, {validator_parse, BadArg}},
            resolve_validators(
                ValSpecs, ValNames, Validators, [Error | Errors], Canned)

    end;
resolve_validators([ValName | ValSpecs], ValNames, Validators, Errors, Canned) ->
    resolve_validators(ValSpecs, [ValName | ValNames], Validators, Errors, Canned);
resolve_validators([], ValNames, Validators, Errors, _Canned) ->
    {lists:reverse(ValNames), Validators, lists:reverse(Errors)}.

-spec scheduler_string_value(Str :: nonempty_string() ) -> integer() | false.
scheduler_string_value(Str) ->
    case string:to_integer(Str) of
        {I, []} when I =< 1024 ->
            I;
        _ ->
            false
    end.

-spec string_percent_check(Str :: nonempty_string() ) -> boolean().
string_percent_check(Str) ->
    case string:to_integer(Str) of
        {I, []} ->
            I >= 1 andalso I =< 100;
        _ ->
            false
    end.

