-spec wordsize_multiple() -> validator().
%% @doc Generate a validator for whole multiples of wordsize.
%%
%% The name of the generated validator is "wordsize-multiple".
wordsize_multiple() ->
    Key = {?MODULE, ?FUNCTION_NAME},
    case erlang:get(Key) of
        Val when erlang:is_tuple(Val) ->
            Val;
        _ ->
            W = integer_value(wordsize),
            S = erlang:integer_to_list(W),
            F = fun(V) ->
                erlang:is_integer(V) andalso (V rem W) =:= 0
            end,
            Res = {validator, "wordsize-multiple",
                    "must be an integer exactly divisible by " ++ S, F},
            erlang:put(Key, Res),
            Res
    end.

