-spec power_of_two() -> validator().
%% @doc Generate a validator for non-negative integral powers of 2.
%%
%% The name of the generated validator is "power-of-two".
power_of_two() ->
    F = fun(V) ->
        erlang:is_integer(V) andalso V >= 0 andalso (V band (V - 1)) =:= 0
    end,
    {validator, "power-of-two", "must be an integral power of two", F}.

-spec schedulers_combined() -> validator().
%% @doc Generate a validator for the 'string' value of the '+S' emulator flag.
%%
%% The name of the generated validator is "scheduler-combined".
schedulers_combined() ->
    CpuCount = integer_value(cpus_count),
    MinCount = if CpuCount < 2 -> 0; true -> (0 - CpuCount + 1) end,
    CpuAvail = integer_value(cpus_avail),
    MinAvail = if CpuAvail < 2 -> 0; true -> (0 - CpuAvail + 1) end,
    F = fun
        ([_|_] = Str) ->
            {Tot, Onl} = case string:split(Str, ":", all) of
                %% It appears that almost any number of trailing colons, with
                %% or without intervening numbers, are allowed and ignored on
                %% the command-line, but we're enforcing the documented
                %% parameter pattern.
                [[_|_] = TotStr] ->
                    {scheduler_string_value(TotStr), 0};
                [[_|_] = TotStr, []] ->
                    {scheduler_string_value(TotStr), 0};
                [[], [_|_] = OnlStr] ->
                    {0, scheduler_string_value(OnlStr)};
                [[_|_] = TotStr, [_|_] = OnlStr] ->
                    {scheduler_string_value(TotStr), scheduler_string_value(OnlStr)};
                _ ->
                    {false, false}
            end,
            if
                Tot =:= false orelse Onl =:= false ->
                    false;
                true ->
                    EffTot = if Tot < 0 -> (Tot + CpuCount); true -> Tot end,
                    EffOnl = if Onl < 0 -> (Onl + CpuAvail); true -> Onl end,
                    EffOnl > 0 andalso EffTot >= EffOnl
            end;
        (_) ->
            false
    end,
    D = lists:concat([
        "must be 'Total', 'Total:Online', or ':Online' when Total is in the"
        " range ", MinCount, "..1024, Online is in the range ",
        MinAvail, "..1024, and effective Total >= effective Online."
    ]),
    {validator, "schedulers-combined", D, F}.

-spec schedulers_percent() -> validator().
%% @doc Generate a validator for the 'string' value of the '+SP' emulator flag.
%%
%% The name of the generated validator is "scheduler-percent".
schedulers_percent() ->
    F = fun
        ([_|_] = Str) ->
            case string:split(Str, ":", all) of
                %% It appears that almost any number of trailing colons, with
                %% or without intervening numbers, are allowed and ignored on
                %% the command-line, but we're enforcing the documented
                %% parameter pattern.
                [[_|_] = TotStr] ->
                    string_percent_check(TotStr);
                [[_|_] = TotStr, []] ->
                    string_percent_check(TotStr);
                [[], [_|_] = OnlStr] ->
                    string_percent_check(OnlStr);
                [[_|_] = TotStr, [_|_] = OnlStr] ->
                    string_percent_check(TotStr) andalso string_percent_check(OnlStr);
                _ ->
                    false
            end;
        (_) ->
            false
    end,
    D = "must be 'Total', 'Total:Online', or ':Online' when Total and Online"
        " are each in the range 1..100",
    {validator, "schedulers-percent", D, F}.

