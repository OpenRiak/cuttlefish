integer_range_test() ->
    RV = integer_range(-7, 12),
    ?assertMatch(
        {validator, "integer:-7..12", _, F} when erlang:is_function(F, 1), RV),
    RF = erlang:element(4, RV),
    ?assertMatch(false, RF(-8)),
    ?assertMatch(true,  RF(-7)),
    ?assertMatch(true,  RF(-6)),
    ?assertMatch(true,  RF(11)),
    ?assertMatch(true,  RF(12)),
    ?assertMatch(false, RF(13)).

integer_value_test() ->
    _ = [?assertMatch(I when erlang:is_integer(I), integer_value(C), C)
        || C <- [cpus_count, cpus_online, cpus_avail, kiloword, wordsize]],
    ?assert(integer_value(cpus_avail) =< integer_value(cpus_online)),
    ?assert(integer_value(cpus_online) =< integer_value(cpus_count)),
    ?assert(integer_value(cpus_count) >= 1),
    ?assertEqual(integer_value(wordsize) * 1024, integer_value(kiloword)),
    ?assertMatch({badarg, {?MODULE, integer_value, [bogus]}}, integer_value(bogus)),
    ?assertMatch({badarg, {?MODULE, integer_value, [_]}}, integer_value(3.14)).

