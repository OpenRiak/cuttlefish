-spec canned_validators() -> list({atom(), arity()}).
%% @private
%% @doc Returns the list of predefined validators as a list of
%% {FuncName, FuncArity} tuples.
canned_validators() ->
    maps:keys(canned()).

-spec resolve_validators(
    Proplist :: proplists:proplist(),
    Validators :: validators(),
    Errors :: list(cuttlefish_error:error()) )
        -> {proplists:proplist(), validators(), list(cuttlefish_error:error())}.
%% @private
%% @doc Resolve predefined validators in Proplist, updating Proplist and Validators.
resolve_validators(Proplist, Validators, Errors) ->
    case proplists:get_value(validators, Proplist, []) of
        [_|_] = ValSpecs ->
            {ValNames, ValidatorsOut, ErrorsOut} =
                resolve_validators(ValSpecs, [], Validators, Errors, canned()),
            ProplistOut = lists:keystore(
                validators, 1, Proplist, {validators, ValNames}),
            {ProplistOut, ValidatorsOut, ErrorsOut};
        _ ->
            {Proplist, Validators, Errors}
    end.

